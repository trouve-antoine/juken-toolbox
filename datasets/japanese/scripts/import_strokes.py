"""Filter a pinned KanjiVG archive into stokes.yaml; no generated geometry."""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tarfile
import xml.etree.ElementTree as ET

BASE = Path(__file__).resolve().parents[1]
REVISION = "55b5ba92a7cad78a62ef04db4be6f9562d949b7f"
ARCHIVE = BASE / "sources/kanjivg-55b5ba92.tar.gz"
NS = {"s": "http://www.w3.org/2000/svg"}


def yaml_read(path):
    return json.loads(subprocess.check_output([
        "/usr/bin/ruby", "-ryaml", "-rjson", "-e",
        "puts JSON.generate(YAML.load_file(ARGV[0]))", str(path)
    ], text=True))


def build():
    characters = list(yaml_read(BASE / "kanji.yaml")["kanji"])
    assert len(characters) == len(set(characters)) == 2136
    data = {}
    with tarfile.open(ARCHIVE, "r:gz") as archive:
        members = {m.name: m for m in archive.getmembers()}
        for char in characters:
            code = f"{ord(char):05x}"
            member = members[f"kanjivg-{REVISION}/kanji/{code}.svg"]
            root = ET.fromstring(archive.extractfile(member).read())
            assert root.attrib["viewBox"] == "0 0 109 109", char
            group = root.find(f"s:g[@id='kvg:StrokePaths_{code}']", NS)
            strokes = group.findall(".//s:path", NS)
            assert strokes, char
            assert [p.attrib["id"] for p in strokes] == [
                f"kvg:{code}-s{i}" for i in range(1, len(strokes) + 1)
            ], char
            # Reject transforms that would be lost by flattening the hierarchy.
            assert not any("transform" in e.attrib for e in group.iter()), char
            paths = [p.attrib["d"] for p in strokes]
            assert all(p.lstrip().startswith(("M", "m")) for p in paths), char
            numbers = root.find(f"s:g[@id='kvg:StrokeNumbers_{code}']", NS)
            labels = []
            for index, label in enumerate(numbers.findall("s:text", NS), 1):
                assert label.text == str(index), (char, label.text)
                match = re.fullmatch(r"matrix\(1 0 0 1 ([\d.+-]+) ([\d.+-]+)\)",
                                     label.attrib["transform"])
                assert match, (char, label.attrib)
                labels.append([float(v) for v in match.groups()])
            assert len(labels) == len(paths), char
            data[char] = {"paths": paths, "labels": labels}

    source = {
        "name": "KanjiVG", "url": "https://kanjivg.tagaini.net/",
        "revision": REVISION, "copyright": "Ulrich Apel",
        "license": "CC-BY-SA-3.0",
        "license_url": "https://creativecommons.org/licenses/by-sa/3.0/",
        "archive_sha256": hashlib.sha256(ARCHIVE.read_bytes()).hexdigest(),
        "changes": "Filtered to kanji.yaml; SVG paths and label positions retained; XML and component metadata omitted.",
    }
    lines = ["# Generated by scripts/import_strokes.py; do not hand-edit geometry.",
             "schema: 1", "source:"]
    for key, value in source.items():
        lines.append(f"  {key}: {json.dumps(value, ensure_ascii=False)}")
    lines.extend(["viewbox: [0, 0, 109, 109]", "", "kanji:"])
    for char, entry in data.items():
        lines.extend([f"  {char}:", "    paths:"])
        lines.extend(f"      - {json.dumps(p)}" for p in entry["paths"])
        lines.append(f"    labels: {json.dumps(entry['labels'])}")
    output = BASE / "stokes.yaml"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Independent YAML parser round-trip checks emitted structure and precision.
    parsed = yaml_read(output)
    assert parsed["kanji"] == data
    assert parsed["source"] == source
    assert set(parsed["kanji"]) == set(characters)
    print(json.dumps({"characters": len(data),
                      "strokes": sum(len(e["paths"]) for e in data.values()),
                      "bytes": output.stat().st_size,
                      "sha256": hashlib.sha256(output.read_bytes()).hexdigest()}))


if __name__ == "__main__":
    build()
